#!/usr/bin/env python3
"""Generate std/unicode_norm.h from the pinned Unicode 16.0.0 UCD files."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UCD = os.path.join(ROOT, "third_party", "ucd-16.0.0")

def version(name):
    with open(os.path.join(UCD, name), encoding="utf-8") as source:
        for line in source:
            found = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
            if found:
                return found.group(1)
    return "16.0.0"

def main():
    assert {version(name) for name in ("UnicodeData.txt", "CompositionExclusions.txt", "NormalizationTest.txt")} == {"16.0.0"}
    exclusions = set()
    with open(os.path.join(UCD, "CompositionExclusions.txt"), encoding="utf-8") as source:
        for line in source:
            line = line.split("#", 1)[0].strip()
            if line:
                exclusions.add(int(line, 16))
    raw, ccc = {}, {}
    with open(os.path.join(UCD, "UnicodeData.txt"), encoding="utf-8") as source:
        for line in source:
            fields = line.rstrip("\n").split(";")
            cp = int(fields[0], 16)
            if fields[3] != "0":
                ccc[cp] = int(fields[3])
            if fields[5]:
                bits = fields[5].split()
                compat = bits[0].startswith("<")
                raw[cp] = (compat, tuple(int(x, 16) for x in bits[1 if compat else 0:]))
    def expand(cp, compat):
        if cp not in raw or (raw[cp][0] and not compat):
            return (cp,)
        return sum((expand(child, compat) for child in raw[cp][1]), ())
    decomp = [(cp, compat, expand(cp, True if compat else False)) for cp, (compat, _) in raw.items()]
    data, entries = [], []
    for cp, compat, values in sorted(decomp):
        entries.append((cp, len(data), len(values), int(compat)))
        data.extend(values)
    composition = []
    for cp, (compat, values) in raw.items():
        if not compat and len(values) == 2 and cp not in exclusions and not ccc.get(values[0], 0):
            composition.append((values[0], values[1], cp))
    print("/* Generated by tools/gen_unicode_norm.py from Unicode 16.0.0. Do not edit. */")
    print("typedef struct { uint32_t cp, at; uint16_t len; uint8_t compat; } unicode_decomp;")
    print("typedef struct { uint32_t cp; uint8_t value; } unicode_ccc;")
    print("typedef struct { uint32_t first, second, composed; } unicode_compose;")
    def emit(name, values, render):
        print("static const " + name + "[] = {")
        for value in values:
            print("  " + render(value) + ",")
        print("};")
    emit("uint32_t UNICODE_DECOMP_DATA", data, lambda x: "%du" % x)
    emit("unicode_decomp UNICODE_DECOMP", entries, lambda x: "{%du,%du,%du,%du}" % x)
    emit("unicode_ccc UNICODE_CCC", sorted(ccc.items()), lambda x: "{%du,%du}" % x)
    emit("unicode_compose UNICODE_COMPOSE", sorted(composition), lambda x: "{%du,%du,%du}" % x)

main()
